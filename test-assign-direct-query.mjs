import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {readManageTaskPage,MANAGE_ACTIVE_VALUES}=require('./functions/manage-task-data.js');
const calls=[];let docs=[];let failure=null;
const query={};for(const method of ['where','orderBy','limit','select','startAfter'])query[method]=(...args)=>{calls.push([method,...args]);return query};
